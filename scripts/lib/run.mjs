// Helpers with side effects.

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  }
  catch {
    return null;
  }
}

function writeJson(file, data) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n');
}

function readText(file) {
  try {
    return fs.readFileSync(file, 'utf8');
  }
  catch {
    return null;
  }
}

/** Every .ddev/config.yaml in the folders above dir, with its contents. */
function outerDdevConfigs(dir) {
  const found = [];
  for (let d = path.dirname(realpath(dir)); path.dirname(d) !== d; d = path.dirname(d)) {
    const file = path.join(d, '.ddev', 'config.yaml');
    const text = readText(file);
    if (text !== null) {
      found.push({ file, text });
    }
  }
  return found;
}

/** Replaces a secret in files, so logs and copied reports never keep it. */
function redactFiles(files, secret) {
  const redacted = [];
  for (const file of files) {
    const text = readText(file);
    if (text?.includes(secret)) {
      fs.writeFileSync(file, text.split(secret).join('[REDACTED]'));
      redacted.push(file);
    }
  }
  return redacted;
}

function realpath(p) {
  try {
    return fs.realpathSync(p);
  }
  catch {
    return path.resolve(p);
  }
}

/** Git in a directory, never walking up into an enclosing repository. */
function gitIn(dir, args) {
  const r = spawnSync('git', ['-C', dir, ...args], {
    encoding: 'utf8',
    timeout: 15 * 60000,
    env: { ...process.env, GIT_TERMINAL_PROMPT: '0', GIT_CEILING_DIRECTORIES: realpath(path.dirname(dir)) },
  });
  return { ok: !r.error && r.status === 0, out: (r.stdout ?? '').trim(), raw: r.stdout ?? '', err: `${r.error?.message ?? ''} ${r.stderr ?? ''}`.trim() };
}

/** Fresh JSON: written at or after `since` (ms). */
function freshJson(file, since) {
  try {
    return fs.statSync(file).mtimeMs >= since ? readJson(file) : null;
  }
  catch {
    return null;
  }
}

/** Every run record of a source. */
export function readRunRecords(root, sourceId) {
  const dir = path.join(root, 'workspaces', 'runs', sourceId);
  if (!fs.existsSync(dir)) {
    return [];
  }
  return fs.readdirSync(dir)
    .filter((d) => d.startsWith('run-'))
    .map((d) => readJson(path.join(dir, d, 'run.json')))
    .filter(Boolean);
}

function lastLine(text) {
  return String(text ?? '').trim().split('\n').filter(Boolean).slice(-1)[0]?.slice(0, 300) ?? '';
}

/** An infrastructure failure of a command; a missing program is a dependency error. */
function commandFailed(what, result) {
  if (result.error?.code === 'ENOENT') {
    return new SourceError(`${what}: command not found`, EXIT.DEPENDENCY);
  }
  const how = result.error ? result.error.message : `exit ${result.code ?? result.signal}`;
  return new SourceError(`${what} failed (${how}): ${lastLine(result.output ?? result.stderr)}`, EXIT.INFRASTRUCTURE);
}

/** Creates or reuses the installation directory and writes its DDEV config and helper files. */
function prepareInstallation(root, sourceId, pinned) {
  const commit = pinned.resolved_commit;
  const rel = path.join('workspaces', 'installations', sourceId, commit);
  const dir = path.join(root, rel);
  const checkoutDir = path.join(root, pinned.checkout);
  const runtime = runtimeVersions(pinned.requirements);
  if (!runtime.php || !runtime.node) {
    throw new SourceError(`cannot choose PHP and Node.js versions from the pinned requirements (php ${pinned.requirements?.php ?? 'unknown'}, node ${pinned.requirements?.node ?? 'unknown'})`, EXIT.INFRASTRUCTURE);
  }
  const name = ddevProjectName(sourceId, commit);
  const reused = fs.existsSync(dir);
  if (reused) {
    const head = gitIn(dir, ['rev-parse', 'HEAD']);
    const top = gitIn(dir, ['rev-parse', '--show-toplevel']);
    if (!head.ok || head.out !== commit || realpath(top.out) !== realpath(dir)) {
      throw new SourceError(`${rel} exists but is not an installation of ${commit}; not touching it`, EXIT.CONFIG);
    }
  }
  else {
    fs.mkdirSync(path.dirname(dir), { recursive: true });
    const add = gitIn(checkoutDir, ['worktree', 'add', '--detach', dir, commit]);
    if (!add.ok) {
      throw new SourceError(`creating the installation failed: ${lastLine(add.err)}`, EXIT.INFRASTRUCTURE);
    }
  }

  const configFile = path.join(dir, '.ddev', 'config.yaml');
  if (fs.existsSync(configFile)) {
    const existing = yaml.load(fs.readFileSync(configFile, 'utf8'));
    if (existing?.name !== name) {
      throw new SourceError(`${rel}/.ddev/config.yaml names the project ${existing?.name}, not ${name}; not touching it`, EXIT.CONFIG);
    }
  }
  else {
    fs.mkdirSync(path.dirname(configFile), { recursive: true });
    fs.writeFileSync(configFile, ddevConfigYaml({ name, sourceId, commit, ...runtime }));
  }

  // Helper files from this repository, in dot directories that the web
  // server does not serve. site-install.php changes to the directory two
  // levels above itself, so it must sit at .agents/scripts/ of the site.
  const copy = (from, to) => fs.cpSync(path.join(root, from), path.join(dir, to), { recursive: true });
  copy('.agents/scripts/site-install.php', '.agents/scripts/site-install.php');
  copy('scripts/observatory/test-account.php', '.observatory/test-account.php');
  copy(`fixtures/recipes/${FIXTURE_RECIPE}`, `.observatory/recipes/${FIXTURE_RECIPE}`);

  return {
    dir,
    rel,
    name,
    reused,
    runtime,
    checkoutDir,
    provenanceFile: `${checkoutDir}.json`,
    baseUrl: `https://${name}.ddev.site`,
    statePath: path.join(dir, '.observatory', 'state.json'),
  };
}

/** Stops unless ddev, run in the installation, resolves to the installation itself. */
function assertDdevTarget(capture, inst) {
  const r = capture('ddev', ['describe', '-j'], { cwd: inst.dir });
  if (r.error?.code === 'ENOENT') {
    throw new SourceError('ddev: command not found', EXIT.DEPENDENCY);
  }
  const target = ddevTarget(r.stdout);
  if (!target || realpath(target.approot) !== realpath(inst.dir) || target.name !== inst.name) {
    const found = target ? `project ${target.name} at ${target.approot}` : `no project (${lastLine(r.stderr) || 'no output'})`;
    throw new SourceError(`ddev in ${inst.rel} resolves to ${found}, not ${inst.name}; stopping before any ddev command runs there`, EXIT.INFRASTRUCTURE);
  }
  return target;
}

function duKb(capture, dir) {
  if (!dir || !fs.existsSync(dir)) {
    return null;
  }
  const r = capture('du', ['-sk', dir]);
  const kb = Number.parseInt(r.stdout, 10);
  return r.code === 0 && Number.isFinite(kb) ? kb : null;
}

function runDirs(dir) {
  return fs.existsSync(dir) ? fs.readdirSync(dir).filter((d) => d.startsWith('run-')) : [];
}

