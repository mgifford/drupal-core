/** Smoke statuses that mean the suite actually exercised the site. */
const SCANNED = new Set(['PASS', 'FAIL', 'INCONCLUSIVE']);
const LOWER_BOUND = /^\s*(?:>=|\^|~|=)?\s*v?(\d+)(?:\.(\d+))?/;

