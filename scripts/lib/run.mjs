/** DDEV project name for an installation, e.g. obs-drupal-core-92e5c3a30476. */
export function ddevProjectName(sourceId, commit) {
  if (!/^[a-z0-9][a-z0-9-]*$/.test(sourceId ?? '') || !/^[0-9a-f]{40}$/.test(commit ?? '')) {
    throw new Error(`cannot name a DDEV project for ${sourceId} ${commit}`);
  }
  return `obs-${sourceId}-${commit.slice(0, 12)}`;
}

/**
 * The lowest PHP minor and Node.js major that the pinned requirements allow,
 * as DDEV wants them ("8.5", "24"). null when a constraint has no lower bound.
 */
export function runtimeVersions(requirements) {
  const php = LOWER_BOUND.exec(requirements?.php ?? '');
  const node = LOWER_BOUND.exec(requirements?.node ?? '');
  return {
    php: php && php[2] !== undefined ? `${php[1]}.${php[2]}` : null,
    node: node ? node[1] : null,
  };
}

/** The installation's .ddev/config.yaml. */
export function ddevConfigYaml({ name, sourceId, commit, php, node }) {
  const config = {
    name,
    type: 'drupal12',
    docroot: '',
    php_version: php,
    webserver_type: 'nginx-fpm',
    database: { ...DATABASE },
    nodejs_version: node,
  };
  return '# Generated by `node scripts/drupal-test.mjs run` for a disposable\n'
    + `# installation of ${sourceId} ${commit}. See docs/testing/RUN.md.\n`
    + yaml.dump(config);
}

/** The project that `ddev describe -j` reports, or null. */
export function ddevTarget(output) {
  for (const line of String(output ?? '').split('\n').reverse()) {
    try {
      const raw = JSON.parse(line)?.raw;
      if (raw?.approot) {
        return { approot: raw.approot, name: raw.name ?? null, status: raw.status ?? null };
      }
    }
    catch {
      // Not a JSON line.
    }
  }
  return null;
}

/**
 * Status of one Playwright run from its JSON report. A missing report, a
 * global error or a nonzero exit without failed tests is an infrastructure
 * error; skipped or flaky tests make a run inconclusive, never a pass.
 */
export function playwrightStatus({ exitCode, report }) {
  if (!report?.stats) {
    return { status: 'INFRASTRUCTURE_ERROR', counts: null, reason: 'no Playwright report from this run' };
  }
  const { expected = 0, unexpected = 0, skipped = 0, flaky = 0 } = report.stats;
  const counts = { passed: expected, failed: unexpected, skipped, flaky };
  const firstError = report.errors?.[0]?.message?.split('\n')[0]?.slice(0, 200);
  if (unexpected > 0) {
    return { status: 'FAIL', counts, reason: `${unexpected} test(s) failed` };
  }
  if (firstError) {
    return { status: 'INFRASTRUCTURE_ERROR', counts, reason: firstError };
  }
  if (exitCode !== 0) {
    return { status: 'INFRASTRUCTURE_ERROR', counts, reason: `Playwright exited ${exitCode ?? 'abnormally'} without a failed test` };
  }
  if (expected + flaky === 0) {
    return { status: skipped ? 'SKIPPED' : 'NOT_RUN', counts, reason: skipped ? 'every test was skipped' : 'no tests ran' };
  }
  if (skipped > 0 || flaky > 0) {
    return { status: 'INCONCLUSIVE', counts, reason: `${skipped} skipped, ${flaky} flaky` };
  }
  return { status: 'PASS', counts, reason: null };
}

/**
 * The run's status. Any infrastructure error wins; otherwise the worst suite
 * result. A pass on code that differs from the pinned commit is inconclusive.
 */
export function overallStatus(stages, { servedCodeChanged = false } = {}) {
  if (stages.some((s) => s.status === 'INFRASTRUCTURE_ERROR')) {
    return 'INFRASTRUCTURE_ERROR';
  }
  const suites = stages.filter((s) => s.suite).map((s) => s.status);
  if (!suites.length) {
    return 'NOT_RUN';
  }
  for (const status of ['FAIL', 'INCONCLUSIVE']) {
    if (suites.includes(status)) {
      return status;
    }
  }
  let status = suites.every((s) => s === suites[0]) ? suites[0] : 'INCONCLUSIVE';
  if (status === 'PASS' && servedCodeChanged) {
    status = 'INCONCLUSIVE';
  }
  return status;
}

/** Exit code for a run status; an infrastructure error keeps its own code. */
export function exitCodeForRun(status, errorCode = null) {
  if (status === 'PASS') {
    return EXIT.OK;
  }
  if (status === 'INFRASTRUCTURE_ERROR') {
    return errorCode ?? EXIT.INFRASTRUCTURE;
  }
  return EXIT.TEST_FAILURE;
}

/** The newest earlier run whose smoke suite exercised a site, or null. */
export function previousScan(records, { excludeRunId = null } = {}) {
  return records
    .filter((r) => r?.run_id && r.run_id !== excludeRunId && r.source?.commit && SCANNED.has(r.suites?.smoke?.status))
    .sort((a, b) => b.run_id.localeCompare(a.run_id))[0] ?? null;
}

const seconds = (ms) => (ms === null || ms === undefined ? '' : `${(ms / 1000).toFixed(1)}s`);
const megabytes = (kb) => (kb === null || kb === undefined ? 'unknown' : `${Math.round(kb / 1024)} MB`);

/** Human-readable summary of a run record. */
export function formatRunSummary(record) {
  const s = record.source ?? {};
  const inst = record.installation;
  const lines = [
    `Observatory run ${record.run_id}: ${record.status} (exit ${record.exit_code})`,
    `  source:        ${s.id} ${s.requested_ref} -> ${s.commit ?? 'not pinned'}${s.commit ? ` (latest known: ${s.is_latest_known ? 'yes' : 'no'})` : ''}`,
  ];
  if (inst) {
    lines.push(`  installation:  ${inst.path} (${inst.reused ? 'reused' : 'created'})`);
    lines.push(`  site:          ${inst.base_url} (DDEV ${inst.ddev_project}, PHP ${inst.php_version ?? 'unknown'}, ${DATABASE.type} ${DATABASE.version}, ${inst.install_profile} + ${inst.recipes.join(', ')})`);
  }
  lines.push('  stages:');
  for (const stage of record.stages) {
    lines.push(`    ${stage.name.padEnd(16)} ${String(stage.status).padEnd(20)} ${seconds(stage.duration_ms).padStart(7)}${stage.detail ? `  ${stage.detail}` : ''}`);
  }
  if (record.disk) {
    lines.push(`  disk:          installation ${megabytes(record.disk.installation_kb)}, checkout ${megabytes(record.disk.checkout_kb)}, source store ${megabytes(record.disk.source_store_kb)} (Docker volumes not counted)`);
  }
  lines.push(`  total time:    ${seconds(record.duration_ms)}`);
  lines.push(`  record:        ${record.record}`);
  for (const note of record.notes) {
    lines.push(`  note: ${note}`);
  }
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Command runners. Tests replace them with fakes.

const activeChildren = new Set();

function stopGroup(child) {
  try {
    process.kill(-child.pid, 'SIGTERM');
  }
  catch {
    child.kill('SIGTERM');
  }
}

/** Runs a command, streaming its output to stderr and to a log file. */
export function execLogged(command, args, { cwd, env, input, logFile, timeoutMs = 60 * 60000 } = {}) {
  return new Promise((resolve) => {
    fs.mkdirSync(path.dirname(logFile), { recursive: true });
    const log = fs.createWriteStream(logFile, { flags: 'a' });
    log.write(`$ ${[command, ...args].join(' ')}\n`);
    let output = '';
    let done = false;
    const finish = (result) => {
      if (!done) {
        done = true;
        activeChildren.delete(child);
        clearTimeout(timer);
        log.end(`\n[exit ${result.code ?? result.signal ?? result.error?.code}]\n`);
        resolve({ ...result, output });
      }
    };
    // Its own process group, so stopping it also stops what it started
    // (npm, Playwright, Chromium).
    const child = spawn(command, args, { cwd, env, detached: true, stdio: [input === undefined ? 'ignore' : 'pipe', 'pipe', 'pipe'] });
    activeChildren.add(child);
    const timer = setTimeout(() => stopGroup(child), timeoutMs);
    const onData = (chunk) => {
      process.stderr.write(chunk);
      log.write(chunk);
      output = (output + chunk).slice(-8000);
    };
    child.stdout?.on('data', onData);
    child.stderr?.on('data', onData);
    if (input !== undefined) {
      child.stdin.on('error', () => {});
      child.stdin.end(input);
    }
    child.on('error', (error) => finish({ code: null, signal: null, error }));
    child.on('close', (code, signal) => finish({ code, signal, error: null }));
  });
}

/** Runs a short command and captures its output. */
export function captureSync(command, args, { cwd, timeoutMs = 120000 } = {}) {
  const r = spawnSync(command, args, { cwd, encoding: 'utf8', timeout: timeoutMs, maxBuffer: 16 * 1024 * 1024 });
  return { code: r.error ? null : r.status, stdout: r.stdout ?? '', stderr: r.stderr ?? '', error: r.error ?? null };
}

