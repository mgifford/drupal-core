/**
 * Pins, builds, tests and records one run. Returns the run record; never
 * throws for a failed stage, which is recorded as INFRASTRUCTURE_ERROR.
 *
 * @param {object} options
 * @param {string} options.root  Repository root (workspaces/ and the tests live here).
 * @param {object} options.config  Loaded config/sources.yml.
 * @param {string} options.sourceId  A git source.
 * @param {string|null} [options.ref]  Commit to pin; default: the branch tip.
 * @param {boolean} [options.offline]
 * @param {string|null} [options.since]  Base commit for the upstream changes.
 * @param {object} [deps]  { exec, capture, log } replacements for tests.
 */
export async function runObservatory(options, deps = {}) {
  const { root, config, sourceId, ref = null } = options;
  const runId = newRunId();
  const lock = acquireRunLock(root, runId);
  const runRel = path.join('workspaces', 'runs', sourceId, runId);
  const runDir = path.join(root, runRel);
  fs.mkdirSync(runDir, { recursive: true });
  const record = {
    schema_version: 1,
    run_id: runId,
    status: 'NOT_RUN',
    exit_code: null,
    started_at: new Date().toISOString(),
    completed_at: null,
    duration_ms: null,
    record: path.join(runRel, 'run.json'),
    source: { id: sourceId, requested_ref: ref ?? config.sources[sourceId]?.branch ?? null, commit: null },
    installation: null,
    stages: [],
    suites: {},
    since: null,
    updates: null,
    disk: null,
    tools: { node: process.version, ddev: null },
    notes: [],
  };
  if (lock.replaced) {
    record.notes.push(`Replaced the lock of an earlier run whose process is gone (${lock.replaced.run_id ?? 'unknown run'}, pid ${lock.replaced.pid ?? 'unknown'}); that run was interrupted.`);
  }

  // Interrupted: stop the current command, record the run and free the lock.
  // The next run repairs whatever the stopped step left behind.
  const onSignal = (signal) => {
    for (const child of activeChildren) {
      stopGroup(child);
    }
    for (const entry of record.stages.filter((s) => s.status === 'running')) {
      entry.status = 'INFRASTRUCTURE_ERROR';
      entry.detail = `interrupted by ${signal}`;
    }
    record.status = 'INFRASTRUCTURE_ERROR';
    record.exit_code = EXIT.INFRASTRUCTURE;
    record.notes.push(`Interrupted by ${signal}.`);
    record.completed_at = new Date().toISOString();
    writeJson(path.join(runDir, 'run.json'), record);
    lock.release();
    process.stderr.write(`\nInterrupted by ${signal}; the record is ${record.record}\n`);
    process.exit(EXIT.INFRASTRUCTURE);
  };
  process.once('SIGINT', onSignal);
  process.once('SIGTERM', onSignal);
  try {
    return await performRun(options, deps, record, runDir);
  }
  catch (error) {
    // A bug or an unexpected filesystem error is not a test result.
    record.status = 'INFRASTRUCTURE_ERROR';
    record.exit_code = EXIT.INFRASTRUCTURE;
    record.notes.push(`The run stopped on an unexpected error: ${error.message}`);
    record.completed_at = new Date().toISOString();
    writeJson(path.join(runDir, 'run.json'), record);
    return record;
  }
  finally {
    process.off('SIGINT', onSignal);
    process.off('SIGTERM', onSignal);
    lock.release();
  }
}

/** The stages of one run; see runObservatory. */
async function performRun(options, deps, record, runDir) {
  const { root, config, sourceId, ref = null, offline = false, since: givenSince = null } = options;
  const exec = deps.exec ?? execLogged;
  const capture = deps.capture ?? captureSync;
  const say = deps.log ?? ((line) => process.stderr.write(`${line}\n`));
  const runId = record.run_id;
  const runRel = path.relative(root, runDir);
  const startedAt = Date.parse(record.started_at);
  const logFile = (name) => path.join(runDir, `${name}.log`);
  const ddevEnv = { ...process.env, DDEV_NONINTERACTIVE: 'true' };

  let failure = null;
  const stage = async (name, fn, { suite = false } = {}) => {
    const entry = { name, status: 'running', started_at: new Date().toISOString(), duration_ms: 0, detail: null };
    if (suite) {
      entry.suite = true;
    }
    record.stages.push(entry);
    if (failure) {
      entry.status = 'NOT_RUN';
      entry.detail = `not run: ${failure.stage} failed`;
      return null;
    }
    say(`==> ${name}`);
    const t0 = Date.now();
    try {
      const result = await fn(entry);
      if (entry.status === 'running') {
        entry.status = 'ok';
      }
      return result;
    }
    catch (error) {
      entry.status = 'INFRASTRUCTURE_ERROR';
      entry.detail = error.message;
      failure = { stage: name, code: error instanceof SourceError ? error.code : EXIT.INFRASTRUCTURE };
      say(`    ${name}: INFRASTRUCTURE_ERROR: ${error.message}`);
      return null;
    }
    finally {
      entry.duration_ms = Date.now() - t0;
    }
  };

  // 1. Pin the upstream commit.
  const pinned = await stage('pin', (entry) => {
    const p = checkoutSource(root, config, sourceId, { ref, offline });
    entry.detail = `${p.resolved_commit}, checkout ${p.reused ? 'reused' : 'created'}`;
    return p;
  });
  if (pinned) {
    record.source = {
      id: sourceId,
      repository: pinned.repository,
      requested_ref: pinned.requested_ref,
      commit: pinned.resolved_commit,
      is_latest_known: pinned.is_latest_known,
      checkout: pinned.checkout,
      provenance_record: `${pinned.checkout}.json`,
    };
  }

  // 2. A disposable installation with its own DDEV project.
  const inst = await stage('installation', (entry) => {
    const i = prepareInstallation(root, sourceId, pinned);
    entry.detail = `${i.reused ? 'reused' : 'created'} ${i.rel}`;
    return i;
  });
  const state = inst ? readJson(inst.statePath) ?? {} : {};
  if (inst) {
    record.installation = {
      path: inst.rel,
      reused: inst.reused,
      ddev_project: inst.name,
      base_url: inst.baseUrl,
      php_version: null,
      database: { ...DATABASE },
      install_profile: INSTALL_PROFILE,
      recipes: [FIXTURE_RECIPE],
      test_account: TEST_USER,
      tracked_changes: null,
    };
  }

  await stage('ddev-register', async (entry) => {
    const version = capture('ddev', ['--version']);
    record.tools.ddev = lastLine(version.stdout) || null;
    // `ddev config` acts on the closest .ddev/config.yaml (the one just
    // written) and registers the project, so later commands resolve to it.
    // As a second line of defence, any project config above the installation
    // must be unchanged afterwards.
    const outer = outerDdevConfigs(inst.dir);
    const r = await exec('ddev', ['config', `--project-name=${inst.name}`], { cwd: inst.dir, env: ddevEnv, logFile: logFile('ddev-register') });
    const changed = outer.filter(({ file, text }) => readText(file) !== text).map(({ file }) => file);
    if (changed.length) {
      throw new SourceError(`ddev config changed ${changed.join(', ')}, outside the installation; stopping. Check that project before using it.`, EXIT.INFRASTRUCTURE);
    }
    if (r.code !== 0) {
      throw commandFailed('ddev config', r);
    }
    assertDdevTarget(capture, inst);
    entry.detail = inst.name;
  });

  let startAttempted = false;
  await stage('ddev-start', async () => {
    startAttempted = true;
    const r = await exec('ddev', ['start', inst.name], { cwd: inst.dir, env: ddevEnv, logFile: logFile('ddev-start') });
    if (r.code !== 0) {
      throw commandFailed('ddev start', r);
    }
    assertDdevTarget(capture, inst);
  });

  // 3. Dependencies, site install, fixtures and the test account.
  await stage('composer-install', async () => {
    const r = await exec('ddev', ['composer', 'install', '--no-interaction', '--no-progress'], { cwd: inst.dir, env: ddevEnv, logFile: logFile('composer-install') });
    if (r.code !== 0) {
      throw commandFailed('composer install', r);
    }
  });

  await stage('site-install', async (entry) => {
    if (state.site_installed_at) {
      entry.status = 'reused';
      entry.detail = `installed ${state.site_installed_at}`;
      return;
    }
    if (state.site_install_started_at) {
      // An earlier run stopped or failed during the install, so this
      // installation's own database is incomplete. Start it again empty.
      assertDdevTarget(capture, inst);
      const reset = await exec('ddev', ['mysql', '-e', 'DROP DATABASE IF EXISTS db; CREATE DATABASE db;'], { cwd: inst.dir, env: ddevEnv, logFile: logFile('site-install') });
      if (reset.code !== 0) {
        throw commandFailed('resetting the incomplete install\'s database', reset);
      }
      record.notes.push(`An earlier install of this installation (started ${state.site_install_started_at}) did not finish; its database was emptied and the site installed again.`);
    }
    // A new install has none of the earlier fixtures.
    delete state.fixtures;
    state.site_install_started_at = new Date().toISOString();
    writeJson(inst.statePath, state);
    const r = await exec('ddev', ['exec', 'php', '.agents/scripts/site-install.php'], { cwd: inst.dir, env: ddevEnv, logFile: logFile('site-install') });
    if (r.code !== 0 || !/^installed$/m.test(r.output)) {
      const error = commandFailed('site install', r);
      error.message += '. If an earlier run stopped part way through the install, remove this installation (docs/testing/RUN.md) and run again.';
      throw error;
    }
    state.site_installed_at = new Date().toISOString();
    state.install_profile = INSTALL_PROFILE;
    writeJson(inst.statePath, state);
    entry.detail = `${INSTALL_PROFILE} profile`;
  });

  await stage('fixtures', async (entry) => {
    if (state.fixtures?.includes(FIXTURE_RECIPE)) {
      entry.status = 'reused';
      entry.detail = FIXTURE_RECIPE;
      return;
    }
    const r = await exec('ddev', ['exec', 'php', 'core/scripts/dr', 'recipe:apply', '--no-interaction', `.observatory/recipes/${FIXTURE_RECIPE}`], { cwd: inst.dir, env: ddevEnv, logFile: logFile('fixtures') });
    if (r.code !== 0) {
      throw commandFailed(`applying the ${FIXTURE_RECIPE} recipe`, r);
    }
    state.fixtures = [FIXTURE_RECIPE];
    writeJson(inst.statePath, state);
    entry.detail = FIXTURE_RECIPE;
  });

  // A new random password every run, passed on stdin and in the test
  // environment only: never written to disk or printed.
  const password = randomBytes(18).toString('base64url');
  await stage('test-account', async (entry) => {
    const r = await exec('ddev', ['exec', 'php', '.observatory/test-account.php', TEST_USER], { cwd: inst.dir, env: ddevEnv, input: `${password}\n`, logFile: logFile('test-account') });
    const uid = /test account uid (\d+)/.exec(r.output)?.[1];
    if (r.code !== 0 || !uid) {
      throw commandFailed('creating the test account', r);
    }
    entry.detail = `${TEST_USER} (uid ${uid}), password rotated`;
  });

  await stage('site-check', async (entry) => {
    const php = capture('ddev', ['exec', 'php', '--version'], { cwd: inst.dir });
    record.installation.php_version = /^PHP (\S+)/m.exec(php.stdout)?.[1] ?? null;
    let code = null;
    for (let attempt = 1; attempt <= 3 && code !== '200'; attempt++) {
      if (attempt > 1) {
        await new Promise((resolve) => setTimeout(resolve, 5000));
      }
      code = capture('curl', ['-sS', '-k', '-o', '/dev/null', '-w', '%{http_code}', '--max-time', '60', `${inst.baseUrl}/user/login`]).stdout.trim();
    }
    if (code !== '200') {
      throw new SourceError(`${inst.baseUrl}/user/login answered ${code || 'nothing'}, not 200`, EXIT.INFRASTRUCTURE);
    }
    // The site must serve the pinned commit. Composer scaffolding may also
    // rewrite tracked files; then it no longer serves exactly that commit.
    const head = gitIn(inst.dir, ['rev-parse', 'HEAD']);
    if (!head.ok || head.out !== pinned.resolved_commit) {
      throw new SourceError(`the installation is at ${head.out || 'an unknown commit'}, not the pinned ${pinned.resolved_commit}`, EXIT.INFRASTRUCTURE);
    }
    const changes = gitIn(inst.dir, ['status', '--porcelain', '--untracked-files=no']);
    record.installation.tracked_changes = changes.ok ? changes.raw.split('\n').filter(Boolean) : null;
    if (!changes.ok) {
      throw new SourceError(`cannot check the installation's tracked files: ${lastLine(changes.err)}`, EXIT.INFRASTRUCTURE);
    }
    if (record.installation.tracked_changes.length) {
      record.notes.push(`The installation's tracked files differ from ${pinned.resolved_commit}: ${record.installation.tracked_changes.join(', ')}. A pass is reported as INCONCLUSIVE.`);
    }
    entry.detail = `200 from /user/login, PHP ${record.installation.php_version ?? 'unknown'}`;
  });

  // 4. The suites. Both run if the site is up; neither stops the other.
  const testEnv = {
    ...process.env,
    DRUPAL_BASE_URL: inst?.baseUrl,
    DRUPAL_SOURCE_DIR: inst?.checkoutDir,
    DRUPAL_TEST_USER: TEST_USER,
    DRUPAL_TEST_PASS: password,
  };
  const reports = path.join(root, 'tests', 'playwright', 'reports');
  await stage('smoke', async (entry) => {
    const t0 = Date.now();
    const r = await exec('npm', ['run', 'test:smoke'], { cwd: root, env: testEnv, logFile: logFile('smoke') });
    const report = freshJson(path.join(reports, 'playwright-results.json'), t0);
    const runInfo = freshJson(path.join(reports, 'run-info.json'), t0);
    if (report) {
      writeJson(path.join(runDir, 'playwright-results.json'), report);
    }
    if (runInfo) {
      writeJson(path.join(runDir, 'run-info.json'), runInfo);
    }
    const result = r.error ? { status: 'INFRASTRUCTURE_ERROR', counts: null, reason: commandFailed('npm run test:smoke', r).message } : playwrightStatus({ exitCode: r.code, report });
    record.suites.smoke = { ...result, results: report ? path.join(runRel, 'playwright-results.json') : null, tested_commit: runInfo?.source?.resolved_commit ?? null };
    entry.status = result.status;
    entry.detail = result.counts
      ? `${result.counts.passed} passed, ${result.counts.failed} failed, ${result.counts.skipped} skipped${result.reason ? ` (${result.reason})` : ''}`
      : result.reason;
  }, { suite: true });

  await stage('evidence', async (entry) => {
    const evidenceRoot = path.join(reports, 'evidence');
    const before = new Set(runDirs(evidenceRoot));
    const r = await exec(process.execPath, [
      'tests/playwright/scripts/evidence.mjs', 'run',
      '--install-profile', INSTALL_PROFILE,
      '--recipes', FIXTURE_RECIPE,
      '--provenance-record', inst.provenanceFile,
    ], { cwd: root, env: testEnv, logFile: logFile('evidence') });
    const created = runDirs(evidenceRoot).filter((d) => !before.has(d));
    const manifestFile = created.length === 1 ? path.join(evidenceRoot, created[0], 'manifest.json') : null;
    const manifest = manifestFile ? readJson(manifestFile) : null;
    let status = manifest?.run?.status ?? 'INFRASTRUCTURE_ERROR';
    let reason = manifest ? null : 'the evidence runner wrote no manifest';
    if (status === 'PASS' && r.code !== 0) {
      status = 'INCONCLUSIVE';
      reason = `the evidence runner exited ${r.code ?? 'abnormally'} for a PASS manifest`;
    }
    record.suites.evidence = {
      status,
      reason,
      run_id: manifest?.run?.run_id ?? null,
      manifest: manifest ? path.relative(root, manifestFile) : null,
      provenance_record: manifest?.target?.source?.provenance_record ?? null,
    };
    entry.status = status;
    entry.detail = manifest ? `${record.suites.evidence.manifest}${reason ? ` (${reason})` : ''}` : reason;
  }, { suite: true });

  // The password must not stay in this run's logs or copied reports.
  const reportFiles = [path.join(reports, 'playwright-results.json'), path.join(reports, 'run-info.json')];
  const redacted = redactFiles([...fs.readdirSync(runDir).map((f) => path.join(runDir, f)), ...reportFiles], password);
  if (redacted.length) {
    record.notes.push(`The test password appeared in ${redacted.map((f) => path.relative(root, f)).join(', ')} and was replaced with [REDACTED].`);
  }
  const testedCommit = record.suites.smoke?.tested_commit;
  const testedOther = Boolean(testedCommit && pinned && testedCommit !== pinned.resolved_commit);
  if (testedOther) {
    record.notes.push(`The smoke run recorded ${testedCommit}, not the pinned ${pinned.resolved_commit}. A pass is reported as INCONCLUSIVE.`);
  }

  // 5. Stop the installation's containers (its database volume stays).
  if (startAttempted) {
    const entry = { name: 'ddev-stop', status: 'ok', started_at: new Date().toISOString(), duration_ms: 0, detail: null };
    const t0 = Date.now();
    try {
      assertDdevTarget(capture, inst);
      const r = await exec('ddev', ['stop', inst.name], { cwd: inst.dir, env: ddevEnv, logFile: logFile('ddev-stop') });
      if (r.code !== 0) {
        throw commandFailed('ddev stop', r);
      }
    }
    catch (error) {
      entry.status = 'warning';
      entry.detail = error.message;
      record.notes.push(`The installation may still be running: ${error.message}`);
    }
    entry.duration_ms = Date.now() - t0;
    record.stages.push(entry);
  }

  // 6. What changed upstream since the previous scanned run.
  const previous = givenSince ? null : previousScan(readRunRecords(root, sourceId), { excludeRunId: runId });
  const since = givenSince ?? previous?.source?.commit ?? null;
  record.since = since ? { commit: since, from: givenSince ? 'given with --since' : `previous scanned run ${previous.run_id}` } : null;
  if (since) {
    try {
      record.updates = sourceUpdates(root, config, sourceId, { since });
    }
    catch (error) {
      record.notes.push(`Upstream changes since ${since} could not be listed: ${error.message}`);
    }
  }
  else {
    record.notes.push(`No earlier scanned run of ${sourceId}; pass --since <commit> to list upstream changes.`);
  }

  // 7. Disk used, status and the record.
  record.disk = {
    installation_kb: duKb(capture, inst?.dir),
    checkout_kb: duKb(capture, inst?.checkoutDir),
    source_store_kb: duKb(capture, config.sources[sourceId]?.directory ? path.resolve(root, config.sources[sourceId].directory) : null),
  };
  record.status = overallStatus(record.stages, { servedCodeChanged: Boolean(record.installation?.tracked_changes?.length) || testedOther });
  record.exit_code = exitCodeForRun(record.status, failure?.code);
  record.completed_at = new Date().toISOString();
  record.duration_ms = Date.now() - startedAt;
  writeJson(path.join(runDir, 'run.json'), record);
  return record;
}
