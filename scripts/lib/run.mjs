/**
 * Manual Observatory run (Phase 3, docs/testing/RUN.md): pin an upstream
 * commit, build a disposable DDEV installation of it, and run the smoke suite
 * and the evidence runner against that site. Nothing here is scheduled.
 *
 * Layout under <root>/workspaces/ (gitignored):
 *   installations/<id>/<commit>/  Git worktree of the pinned commit, used as
 *                                 its own DDEV project. It gains .ddev/,
 *                                 vendor/, settings files and .observatory/
 *                                 (helper files and state.json). Reused for
 *                                 later runs of the same commit.
 *   runs/<id>/<run-id>/           run.json, one log per stage, and copies of
 *                                 the Playwright results.
 *
 * One run at a time: workspaces/state/run.lock names the running process. A
 * lock left by a process that no longer exists is replaced, and an install
 * that an interrupted run left incomplete is redone on the installation's own
 * database, so an unattended caller can simply run again.
 *
 * The DDEV project at the repository root is never used. DDEV 1.25 sends a
 * command run inside an unregistered nested project to the registered
 * project around it, so each installation is registered with `ddev config`
 * first, and `ddev describe` must name the installation itself before any
 * other ddev command runs there.
 */
