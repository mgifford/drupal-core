/** True when a process with this pid exists (EPERM means it exists). */
export function processAlive(pid) {
  if (!Number.isInteger(pid) || pid <= 0) {
    return false;
  }
  try {
    process.kill(pid, 0);
    return true;
  }
  catch (error) {
    return error.code === 'EPERM';
  }
}

/**
 * Takes workspaces/state/run.lock. Refuses while the process that holds it is
 * alive; replaces a lock whose process is gone (an interrupted run) and
 * reports it in `replaced`. workspaces/ is local to one machine, so the pid
 * decides; the host name is recorded for people only, because macOS changes
 * it with the network.
 */
export function acquireRunLock(root, runId, { isAlive = processAlive, host = os.hostname() } = {}) {
  const file = path.join(root, 'workspaces', 'state', 'run.lock');
  const rel = path.relative(root, file);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const mine = { pid: process.pid, host, run_id: runId, started_at: new Date().toISOString() };
  let replaced = null;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      fs.writeFileSync(file, JSON.stringify(mine) + '\n', { flag: 'wx' });
      const release = () => {
        if (readJson(file)?.run_id === runId) {
          fs.rmSync(file, { force: true });
        }
      };
      return { file, replaced, release };
    }
    catch (error) {
      if (error.code !== 'EEXIST') {
        throw error;
      }
    }
    let age;
    try {
      age = Date.now() - fs.statSync(file).mtimeMs;
    }
    catch {
      continue;
    }
    const holder = readJson(file);
    const busy = () => new SourceError(holder
      ? `another run is in progress (${holder.run_id}, pid ${holder.pid}, since ${holder.started_at}); not starting. If no run is active, delete ${rel}.`
      : `${rel} is being written by another run; not starting`, EXIT.INFRASTRUCTURE);
    if (holder ? isAlive(holder.pid) : age <= 60000) {
      throw busy();
    }
    // Take the stale lock aside atomically, and check that it is still the
    // one judged stale: another run may have replaced it in the meantime.
    const aside = `${file}.${runId}`;
    try {
      fs.renameSync(file, aside);
    }
    catch {
      continue;
    }
    const moved = readJson(aside);
    if (moved?.run_id !== holder?.run_id || moved?.pid !== holder?.pid) {
      // Another run's fresh lock: put it back without overwriting anything.
      try {
        fs.linkSync(aside, file);
      }
      catch {
        // A third run holds the lock now; it stays.
      }
      fs.rmSync(aside, { force: true });
      throw new SourceError(`another run took ${rel} first; not starting`, EXIT.INFRASTRUCTURE);
    }
    fs.rmSync(aside, { force: true });
    replaced = holder ?? { run_id: null, pid: null };
  }
  throw new SourceError(`could not take ${rel}`, EXIT.INFRASTRUCTURE);
}

