test('playwrightStatus never turns a missing, failed, skipped or broken run into a pass', () => {
  const stats = (s) => ({ stats: { expected: 0, unexpected: 0, skipped: 0, flaky: 0, ...s }, errors: [] });
  assert.equal(playwrightStatus({ exitCode: 0, report: null }).status, 'INFRASTRUCTURE_ERROR');
  assert.equal(playwrightStatus({ exitCode: 1, report: stats({ expected: 4, unexpected: 1 }) }).status, 'FAIL');
  assert.equal(playwrightStatus({ exitCode: 1, report: { ...stats({}), errors: [{ message: 'globalSetup failed\nstack' }] } }).reason, 'globalSetup failed');
  assert.equal(playwrightStatus({ exitCode: 1, report: stats({ expected: 5 }) }).status, 'INFRASTRUCTURE_ERROR');
  assert.equal(playwrightStatus({ exitCode: 0, report: stats({ skipped: 5 }) }).status, 'SKIPPED');
  assert.equal(playwrightStatus({ exitCode: 0, report: stats({}) }).status, 'NOT_RUN');
  assert.equal(playwrightStatus({ exitCode: 0, report: stats({ expected: 2, skipped: 3 }) }).status, 'INCONCLUSIVE');
  assert.equal(playwrightStatus({ exitCode: 0, report: stats({ expected: 4, flaky: 1 }) }).status, 'INCONCLUSIVE');
  assert.deepEqual(playwrightStatus({ exitCode: 0, report: stats({ expected: 5 }) }), { status: 'PASS', counts: { passed: 5, failed: 0, skipped: 0, flaky: 0 }, reason: null });
});

