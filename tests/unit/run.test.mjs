function sh(cwd, ...args) {
  return execFileSync('git', ['-c', 'user.email=test@example.com', '-c', 'user.name=Test', ...args], { cwd, encoding: 'utf8' }).trim();
}

/** A repository root with a file:// upstream, the helper files and the reports folder. */
function fixture() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'drupal-test-run-'));
  const upstream = path.join(tmp, 'upstream');
  const root = path.join(tmp, 'engine');
  fs.mkdirSync(upstream);
  sh(upstream, 'init', '-q', '-b', 'main');
  const files = {
    'core/composer.json': JSON.stringify({ require: { php: '>=8.5.0' } }),
    'core/package.json': JSON.stringify({ engines: { node: '>= 24.0' } }),
    'index.php': '<?php\n',
  };
  for (const [file, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(upstream, file)), { recursive: true });
    fs.writeFileSync(path.join(upstream, file), content);
  }
  sh(upstream, 'add', '-A');
  sh(upstream, 'commit', '-q', '-m', 'Initial commit');
  const commit = sh(upstream, 'rev-parse', 'HEAD');
  for (const [file, content] of Object.entries({
    '.agents/scripts/site-install.php': '<?php echo "installed\\n";\n',
    'scripts/observatory/test-account.php': '<?php\n',
    'fixtures/recipes/observatory_smoke/recipe.yml': 'name: test\n',
  })) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    fs.writeFileSync(path.join(root, file), content);
  }
  const config = {
    schema_version: 1,
    defaults: { source: 'core', refresh_before_run: true },
    sources: { core: { type: 'git', url: `file://${upstream}`, branch: 'main', directory: 'workspaces/sources/core' } },
  };
  return { tmp, root, config, commit, upstream };
}

/**
 * Fake command runners. `ddev describe` reports the project named in the
 * closest .ddev/config.yaml, as DDEV does for a registered project, unless
 * `outer` is set: then it reports the outer project, as DDEV 1.25 does for
 * an unregistered nested one.
 */
function fakes(root, { fail = null, outer = false, smoke = { expected: 5 }, ddevMissing = false } = {}) {
  const calls = [];
  const reports = path.join(root, 'tests/playwright/reports');
  const exec = async (command, args, opts) => {
    calls.push({ command, args, cwd: opts.cwd, input: opts.input, env: opts.env });
    const line = [path.basename(command), ...args].join(' ');
    if (ddevMissing && command === 'ddev') {
      return { code: null, error: Object.assign(new Error('spawn ddev ENOENT'), { code: 'ENOENT' }), output: '' };
    }
    if (fail && line.includes(fail)) {
      return { code: 1, error: null, output: `${fail} broke\n` };
    }
    if (line.includes('site-install.php')) {
      return { code: 0, error: null, output: 'installed\n' };
    }
    if (line.includes('test-account.php')) {
      return { code: 0, error: null, output: `created test account uid 2\n` };
    }
    if (command === 'npm') {
      fs.mkdirSync(reports, { recursive: true });
      const stats = { expected: 0, unexpected: 0, skipped: 0, flaky: 0, ...smoke };
      fs.writeFileSync(path.join(reports, 'playwright-results.json'), JSON.stringify({ stats, errors: [] }));
      fs.writeFileSync(path.join(reports, 'run-info.json'), JSON.stringify({ source: { resolved_commit: execFileSync('git', ['-C', opts.env.DRUPAL_SOURCE_DIR, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim() } }));
      return { code: stats.unexpected ? 1 : 0, error: null, output: '' };
    }
    if (line.includes('evidence.mjs run')) {
      const dir = path.join(reports, 'evidence', `run-20990101T000000Z-${String(calls.length).padStart(8, '0')}`);
      fs.mkdirSync(dir, { recursive: true });
      const record = args[args.indexOf('--provenance-record') + 1];
      fs.writeFileSync(path.join(dir, 'manifest.json'), JSON.stringify({ run: { run_id: path.basename(dir), status: 'PASS' }, target: { source: { provenance_record: fs.existsSync(record) ? 'source-provenance.json' : null } } }));
      return { code: 0, error: null, output: '' };
    }
    return { code: 0, error: null, output: '' };
  };
  const capture = (command, args, opts = {}) => {
    calls.push({ command, args, cwd: opts.cwd, capture: true });
    if (ddevMissing && command === 'ddev') {
      return { code: null, stdout: '', stderr: '', error: Object.assign(new Error('ENOENT'), { code: 'ENOENT' }) };
    }
    if (command === 'ddev' && args[0] === 'describe') {
      const name = yaml.load(fs.readFileSync(path.join(opts.cwd, '.ddev/config.yaml'), 'utf8')).name;
      const raw = outer ? { approot: root, name: 'drupal-core' } : { approot: opts.cwd, name, status: 'running' };
      return { code: 0, stdout: JSON.stringify({ level: 'info', raw }), stderr: '', error: null };
    }
    if (command === 'ddev' && args[0] === '--version') {
      return { code: 0, stdout: 'ddev version v1.25.5\n', stderr: '', error: null };
    }
    if (command === 'ddev' && args.join(' ') === 'exec php --version') {
      return { code: 0, stdout: 'PHP 8.5.1 (cli)\n', stderr: '', error: null };
    }
    if (command === 'curl') {
      return { code: 0, stdout: '200', stderr: '', error: null };
    }
    if (command === 'du') {
      return { code: 0, stdout: `2048\t${args[1]}\n`, stderr: '', error: null };
    }
    return { code: 0, stdout: '', stderr: '', error: null };
  };
  return { calls, deps: { exec, capture, log: () => {} } };
}

const ddevCalls = (calls) => calls.filter((c) => c.command === 'ddev' && !c.capture).map((c) => c.args.join(' '));

test('a run pins, builds, tests and records; a second run reuses the installation', async () => {
  const { tmp, root, config, commit } = fixture();
  try {
    const { calls, deps } = fakes(root);
    const record = await runObservatory({ root, config, sourceId: 'core' }, deps);
    assert.equal(record.status, 'PASS', JSON.stringify(record.stages, null, 2));
    assert.equal(record.exit_code, EXIT.OK);
    assert.equal(record.source.commit, commit);
    assert.equal(record.source.is_latest_known, true);
    assert.equal(record.source.provenance_record, `workspaces/checkouts/core/${commit}.json`);
    assert.deepEqual(record.stages.map((s) => s.name), ['pin', 'installation', 'ddev-register', 'ddev-start', 'composer-install', 'site-install', 'fixtures', 'test-account', 'site-check', 'smoke', 'evidence', 'ddev-stop']);

    // The installation is its own worktree and DDEV project; the checkout stays clean.
    const inst = path.join(root, 'workspaces/installations/core', commit);
    const name = `obs-core-${commit.slice(0, 12)}`;
    assert.equal(record.installation.ddev_project, name);
    assert.equal(record.installation.base_url, `https://${name}.ddev.site`);
    assert.equal(record.installation.php_version, '8.5.1');
    assert.deepEqual(record.installation.tracked_changes, []);
    assert.equal(yaml.load(fs.readFileSync(path.join(inst, '.ddev/config.yaml'), 'utf8')).php_version, '8.5');
    assert.ok(fs.existsSync(path.join(inst, '.agents/scripts/site-install.php')));
    assert.ok(fs.existsSync(path.join(inst, '.observatory/recipes/observatory_smoke/recipe.yml')));
    assert.equal(execFileSync('git', ['-C', path.join(root, record.source.checkout), 'status', '--porcelain'], { encoding: 'utf8' }), '');

    // Every ddev command ran in the installation, start and stop by name.
    assert.ok(calls.filter((c) => c.command === 'ddev').every((c) => c.cwd === inst || c.args[0] === '--version'));
    assert.deepEqual(ddevCalls(calls), [
      `config --project-name=${name}`,
      `start ${name}`,
      'composer install --no-interaction --no-progress',
      'exec php .agents/scripts/site-install.php',
      'exec php core/scripts/dr recipe:apply --no-interaction .observatory/recipes/observatory_smoke',
      `exec php .observatory/test-account.php ${TEST_USER}`,
      `stop ${name}`,
    ]);

    // The password goes in on stdin and into the test environment only.
    const password = calls.find((c) => c.args.includes(TEST_USER)).input.trim();
    assert.ok(password.length >= 16);
    const smoke = calls.find((c) => c.command === 'npm');
    assert.equal(smoke.env.DRUPAL_TEST_PASS, password);
    assert.equal(smoke.env.DRUPAL_TEST_USER, TEST_USER);
    assert.equal(smoke.env.DRUPAL_BASE_URL, `https://${name}.ddev.site`);
    assert.equal(smoke.env.DRUPAL_SOURCE_DIR, path.join(root, record.source.checkout));
    const runDir = path.join(root, 'workspaces/runs/core', record.run_id);
    for (const file of fs.readdirSync(runDir)) {
      assert.ok(!fs.readFileSync(path.join(runDir, file), 'utf8').includes(password), `${file} holds the password`);
    }

    // Suites and the evidence manifest.
    assert.equal(record.suites.smoke.status, 'PASS');
    assert.equal(record.suites.smoke.tested_commit, commit);
    assert.equal(record.suites.evidence.status, 'PASS');
    assert.equal(record.suites.evidence.provenance_record, 'source-provenance.json');
    assert.equal(record.disk.installation_kb, 2048);
    assert.equal(record.since, null);
    assert.match(record.notes.join(' '), /No earlier scanned run/);
    assert.deepEqual(JSON.parse(fs.readFileSync(path.join(runDir, 'run.json'), 'utf8')).run_id, record.run_id);
    assert.match(formatRunSummary(record), /: PASS \(exit 0\)/);

    // A second run of the same commit reuses the installation and the site,
    // rotates the password, and lists upstream changes since the first run.
    const second = fakes(root);
    const again = await runObservatory({ root, config, sourceId: 'core' }, second.deps);
    assert.equal(again.status, 'PASS');
    assert.equal(again.installation.reused, true);
    assert.equal(again.stages.find((s) => s.name === 'site-install').status, 'reused');
    assert.equal(again.stages.find((s) => s.name === 'fixtures').status, 'reused');
    assert.ok(!ddevCalls(second.calls).some((c) => c.includes('site-install.php')));
    assert.notEqual(second.calls.find((c) => c.args.includes(TEST_USER)).input.trim(), password);
    assert.equal(again.since.commit, commit);
    assert.match(again.since.from, new RegExp(record.run_id));
    assert.equal(again.updates.commit_count, 0);
  }
  finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
});

