  assert.equal(overallStatus([ok, suite('SKIPPED'), suite('SKIPPED')]), 'SKIPPED');
  assert.equal(overallStatus([ok]), 'NOT_RUN');
  assert.equal(overallStatus([ok, suite('PASS'), suite('PASS'), { name: 'ddev-stop', status: 'warning' }]), 'PASS');
