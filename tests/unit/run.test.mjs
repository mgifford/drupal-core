test('one run at a time: a live lock refuses, a lock left by a gone process is replaced', async () => {
  const { tmp, root, config } = fixture();
  try {
    const lockFile = path.join(root, 'workspaces/state/run.lock');
    fs.mkdirSync(path.dirname(lockFile), { recursive: true });
    // This process is alive, so its lock holds.
    fs.writeFileSync(lockFile, JSON.stringify({ pid: process.pid, host: os.hostname(), run_id: 'run-busy', started_at: 'now' }));
    await assert.rejects(runObservatory({ root, config, sourceId: 'core' }, fakes(root).deps), (error) => {
      assert.equal(error.code, EXIT.INFRASTRUCTURE);
      assert.match(error.message, /another run is in progress \(run-busy/);
      return true;
    });
    assert.ok(!fs.existsSync(path.join(root, 'workspaces/runs')), 'a refused run leaves no record');
    // A lock whose process is gone belongs to an interrupted run, even if
    // the host name changed since (macOS renames hosts with the network).
    fs.writeFileSync(lockFile, JSON.stringify({ pid: process.pid, host: 'old-name.local', run_id: 'run-gone' }));
    const lock = acquireRunLock(root, 'run-new', { isAlive: () => false });
    assert.equal(lock.replaced.run_id, 'run-gone');
    lock.release();
    assert.ok(!fs.existsSync(lockFile));
    // Two runs judge the same lock stale: the second must not remove the
    // lock the first one has just taken.
    fs.writeFileSync(lockFile, JSON.stringify({ pid: 999, run_id: 'run-gone' }));
    const isAlive = () => {
      fs.writeFileSync(lockFile, JSON.stringify({ pid: process.pid, run_id: 'run-first' }));
      return false;
    };
    assert.throws(() => acquireRunLock(root, 'run-second', { isAlive }), /another run took/);
    assert.equal(JSON.parse(fs.readFileSync(lockFile, 'utf8')).run_id, 'run-first');
    assert.deepEqual(fs.readdirSync(path.dirname(lockFile)), ['run.lock']);
    fs.rmSync(lockFile);
    // release() never removes another run's lock.
    const mine = acquireRunLock(root, 'run-a');
    fs.writeFileSync(lockFile, JSON.stringify({ pid: 1, host: os.hostname(), run_id: 'run-b' }));
    mine.release();
    assert.ok(fs.existsSync(lockFile));
    fs.rmSync(lockFile);
    // A completed run frees the lock.
    const done = await runObservatory({ root, config, sourceId: 'core' }, fakes(root).deps);
    assert.equal(done.status, 'PASS');
    assert.ok(!fs.existsSync(lockFile));
  }
  finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
});

