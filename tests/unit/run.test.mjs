test('SIGTERM during a run records it, stops the command and frees the lock', async () => {
  const { tmp, root, config } = fixture();
  try {
    // A child process runs the real runObservatory with fakes; Composer hangs.
    const script = path.join(tmp, 'interrupted-run.mjs');
    fs.writeFileSync(script, `
      import fs from 'node:fs';
      import path from 'node:path';
      import { runObservatory } from ${JSON.stringify(path.join(REPO, 'scripts/lib/run.mjs'))};
      const [root, config] = [process.argv[2], JSON.parse(process.argv[3])];
      const exec = (command, args) => args.includes('composer')
        ? (console.log('composer started'), new Promise(() => setInterval(() => {}, 1000)))
        : Promise.resolve({ code: 0, error: null, output: '' });
      const capture = (command, args, opts = {}) => {
        if (args[0] === 'describe') {
          const name = /name: (\\S+)/.exec(fs.readFileSync(path.join(opts.cwd, '.ddev/config.yaml'), 'utf8'))[1];
          return { code: 0, stdout: JSON.stringify({ raw: { approot: opts.cwd, name } }), stderr: '', error: null };
        }
        return { code: 0, stdout: '', stderr: '', error: null };
      };
      await runObservatory({ root, config, sourceId: 'core' }, { exec, capture, log: () => {} });
    `);
    const { spawn } = await import('node:child_process');
    const child = spawn(process.execPath, [script, root, JSON.stringify(config)], { stdio: ['ignore', 'pipe', 'pipe'] });
    let stderr = '';
    child.stderr.on('data', (d) => { stderr += d; });
    await new Promise((resolve, reject) => {
      child.stdout.on('data', (d) => String(d).includes('composer started') && resolve());
      child.on('exit', () => reject(new Error(`exited early: ${stderr}`)));
    });
    const exited = new Promise((resolve) => child.on('exit', (code) => resolve(code)));
    child.kill('SIGTERM');
    assert.equal(await exited, EXIT.INFRASTRUCTURE);
    const runs = fs.readdirSync(path.join(root, 'workspaces/runs/core'));
    const record = JSON.parse(fs.readFileSync(path.join(root, 'workspaces/runs/core', runs[0], 'run.json'), 'utf8'));
    assert.equal(record.status, 'INFRASTRUCTURE_ERROR');
    assert.deepEqual(record.stages.find((s) => s.name === 'composer-install'), { ...record.stages.find((s) => s.name === 'composer-install'), status: 'INFRASTRUCTURE_ERROR', detail: 'interrupted by SIGTERM' });
    assert.match(record.notes.join(' '), /Interrupted by SIGTERM/);
    assert.ok(!fs.existsSync(path.join(root, 'workspaces/state/run.lock')));
  }
  finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
});

