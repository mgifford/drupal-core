test('the test password is redacted from run logs and copied reports', async () => {
  const { tmp, root, config } = fixture();
  try {
    const { calls, deps } = fakes(root);
    const exec = deps.exec;
    deps.exec = async (command, args, opts) => {
      const result = await exec(command, args, opts);
      if (command === 'npm') {
        // A failure message that quotes the typed value.
        const file = path.join(root, 'tests/playwright/reports/playwright-results.json');
        const report = JSON.parse(fs.readFileSync(file, 'utf8'));
        fs.writeFileSync(file, JSON.stringify({ ...report, note: `fill("${opts.env.DRUPAL_TEST_PASS}")` }));
        fs.writeFileSync(opts.logFile, `typed ${opts.env.DRUPAL_TEST_PASS}\n`);
      }
      return result;
    };
    const record = await runObservatory({ root, config, sourceId: 'core' }, deps);
    const password = calls.find((c) => c.command === 'npm').env.DRUPAL_TEST_PASS;
    const runDir = path.join(root, 'workspaces/runs/core', record.run_id);
    for (const file of [...fs.readdirSync(runDir).map((f) => path.join(runDir, f)), path.join(root, 'tests/playwright/reports/playwright-results.json')]) {
      assert.ok(!fs.readFileSync(file, 'utf8').includes(password), `${file} holds the password`);
    }
    assert.match(fs.readFileSync(path.join(runDir, 'smoke.log'), 'utf8'), /typed \[REDACTED\]/);
    assert.match(record.notes.join(' '), /replaced with \[REDACTED\]/);
  }
  finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
});

